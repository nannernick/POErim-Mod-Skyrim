#!/usr/bin/env python3
"""Builds data/DiabloInSkyrim.esp reproducibly: ESL-flagged, master Skyrim.esm.

Contents (FormIDs frozen, never renumber):
  0x800  KYWD DIS_CurrencyOrb
  0x801+ MISC one per orb, in roll::Orb order (src/roll/Craft.h); 0x809 is the
         Regal Orb (2.1.0)

No MODL on purpose: the plugin gives EVERY orb the same small vanilla cut-gem
mesh at load (Orbs.cpp PickGemModel) and attaches the vanilla VendorItemGem
keyword, so this file references nothing in Skyrim.esm by FormID and cannot
point an orb at a container or chest mesh.
Run:  python tools/esp/build_esp.py data/DiabloInSkyrim.esp
"""
import struct, sys

ORBS = [  # editor id, name, value -- roll::Orb order (weight 0)
    ("DIS_OrbTransmute", "Orb of Transmutation", 5),
    ("DIS_OrbAugment", "Orb of Augmentation", 8),
    ("DIS_OrbAlchemy", "Orb of Alchemy", 40),
    ("DIS_OrbExalt", "Exalted Orb", 150),
    ("DIS_OrbChaos", "Chaos Orb", 60),
    ("DIS_OrbScour", "Orb of Scouring", 30),
    ("DIS_OrbDivine", "Divine Orb", 400),
    ("DIS_OrbVaal", "Vaal Orb", 100),
    ("DIS_OrbRegal", "Regal Orb", 50),
]
OWN = 0x01000000  # one master: own forms are file index 01

def sub(tag, data):
    return tag.encode() + struct.pack("<H", len(data)) + data

def zs(s):
    return s.encode("cp1252") + b"\0"

def record(tag, formid, flags, fields):
    body = b"".join(fields)
    return tag.encode() + struct.pack("<IIIIHH", len(body), flags, formid, 0, 44, 0) + body

def group(label, records):
    body = b"".join(records)
    return b"GRUP" + struct.pack("<I4sIIHH", 24 + len(body), label.encode(), 0, 0, 0, 0) + body

def build():
    kywd = record("KYWD", OWN | 0x800, 0, [sub("EDID", zs("DIS_CurrencyOrb")),
                                           sub("CNAM", struct.pack("<BBBB", 230, 195, 100, 0))])
    miscs = []
    for i, (edid, name, value) in enumerate(ORBS):
        miscs.append(record("MISC", OWN | (0x801 + i), 0, [
            sub("EDID", zs(edid)),
            sub("OBND", struct.pack("<6h", -4, -4, -4, 4, 4, 4)),
            sub("FULL", zs(name)),
            sub("KSIZ", struct.pack("<I", 1)),
            sub("KWDA", struct.pack("<I", OWN | 0x800)),
            sub("DATA", struct.pack("<if", value, 0.0)),
        ]))
    count = 1 + len(miscs)
    tes4 = record("TES4", 0, 0x200, [   # 0x200 = ESL (light plugin)
        sub("HEDR", struct.pack("<fII", 1.71, count, 0x810)),
        sub("CNAM", zs("POErim")),
        sub("SNAM", zs("POErim currency orbs. Generated by tools/esp/build_esp.py")),
        sub("MAST", zs("Skyrim.esm")),
        sub("DATA", struct.pack("<Q", 0)),
    ])
    return tes4 + group("KYWD", [kywd]) + group("MISC", miscs)

if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else "data/DiabloInSkyrim.esp"
    with open(out, "wb") as f:
        f.write(build())
    print(f"wrote {out}")
